r"""
maintenance.py — PC maintenance utilities for WinDesktopMgr (Maintenance tab).

Tier 1: junk / temp cleanup. Scan is read-only and always runs first so the UI
can preview exactly what will be removed and how much space it frees; cleaning
only ever touches the whitelisted category roots below — the API takes category
KEYS, never caller-supplied paths, so there is no path-traversal surface.

Design choices (carried over from the drive-swap review):
  * Preview-first: `scan_junk()` reports count/bytes/samples per category with
    no side effects; `clean_junk(keys)` acts only on those keys.
  * Safe-by-default: only USER-SCOPE junk that needs no elevation is deleted
    here (temp, caches, crash dumps, WER, Recycle Bin — all regenerated by
    Windows/apps). SYSTEM-SCOPE junk (C:\Windows\Temp, Windows Update payloads)
    is deliberately NOT deleted by this process; the tab hands those off to
    Windows' own Disk Cleanup (cleanmgr), which elevates through Windows itself
    — so the app never runs an elevated file-deleter of its own.
  * Python-first: os.scandir / os.remove / shutil.rmtree, with a ctypes
    SHFileOperation for the Recycle-Bin option and SHQuery/EmptyRecycleBin for
    the bin itself. No PowerShell.
"""

