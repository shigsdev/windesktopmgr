def _send_to_recycle_bin(path: str) -> bool:
    """Delete ``path`` to the Recycle Bin via SHFileOperationW. Returns success."""

    class SHFILEOPSTRUCTW(ctypes.Structure):
        _fields_ = [
            ("hwnd", wintypes.HWND),
            ("wFunc", wintypes.UINT),
            ("pFrom", wintypes.LPCWSTR),
            ("pTo", wintypes.LPCWSTR),
            ("fFlags", ctypes.c_uint16),
            ("fAnyOperationsAborted", wintypes.BOOL),
            ("hNameMappings", ctypes.c_void_p),
            ("lpszProgressTitle", wintypes.LPCWSTR),
        ]

    op = SHFILEOPSTRUCTW()
    op.wFunc = _FO_DELETE
    op.pFrom = path + "\0\0"  # double-null terminated list
    op.fFlags = _FOF_ALLOWUNDO | _FOF_NOCONFIRMATION | _FOF_SILENT | _FOF_NOERRORUI
    try:
        rc = ctypes.windll.shell32.SHFileOperationW(ctypes.byref(op))
    except Exception:  # noqa: BLE001
        return False
    return rc == 0 and not op.fAnyOperationsAborted


def _delete_entry(path: str, *, to_recycle_bin: bool) -> bool:
    if to_recycle_bin:
        return _send_to_recycle_bin(path)
    try:
        if os.path.isdir(path) and not os.path.islink(path):
            shutil.rmtree(path, ignore_errors=True)
            return not os.path.exists(path)
        os.remove(path)
        return True
    except OSError:
        return False


def _empty_recycle_bin() -> tuple[int, bool]:
    """Empty the Recycle Bin (all drives). Returns (bytes_freed_estimate, ok)."""
    _, nbytes = _recycle_bin_info()
    try:
        # NULL path = all drives; flags: no confirmation/progress/sound.
        rc = ctypes.windll.shell32.SHEmptyRecycleBinW(None, None, 0x00000001 | 0x00000002 | 0x00000004)
    except Exception:  # noqa: BLE001
        return (0, False)
    return (nbytes, rc == 0)


def clean_junk(keys: list[str]) -> dict:
    """Delete the junk in the given category keys. Only whitelisted keys act;
    unknown keys are ignored. Per-category counts + a grand total are returned.
    'caution'-risk categories go to the Recycle Bin so they stay recoverable;
    'safe' ones are removed permanently (they are regenerated on demand)."""
    by_key = {c["key"]: c for c in _junk_categories()}
    wanted = [by_key[k] for k in (keys or []) if k in by_key]
    results = []
    total_freed = 0
    for c in wanted:
        freed = 0
        removed = 0
        errors = 0
        if c.get("special") == "recycle_bin":
            freed, ok = _empty_recycle_bin()
            removed = 1 if ok else 0
            errors = 0 if ok else 1
        else:
            to_bin = c.get("risk") == "caution"
            recurse = c.get("recurse", True)
            for root in _resolved_roots(c):  # confined to the profile, de-duped
                if not os.path.isdir(root):
                    continue
                try:
                    entries = list(os.scandir(root))
                except OSError:
                    continue
                cutoff = time.time() - (c.get("min_age_days", 0) * 86400) if c.get("min_age_days") else None
                for entry in entries:
                    try:
                        if not _matches(entry.name, c.get("patterns")):
                            continue
                        sz = 0
                        if entry.is_file(follow_symlinks=False):
                            if cutoff is not None and entry.stat(follow_symlinks=False).st_mtime > cutoff:
                                continue
                            sz = entry.stat(follow_symlinks=False).st_size
                        elif entry.is_dir(follow_symlinks=False):
                            if not recurse or _is_reparse(entry):
                                continue  # never delete through a junction; honor recurse=False
                            if cutoff is not None and (
                                entry.stat(follow_symlinks=False).st_mtime > cutoff
                                or _tree_has_recent(entry.path, cutoff)
                            ):
                                continue  # dir holds fresh files — leave it alone
                            _, sz, _ = _scan_dir(entry.path, min_age_days=0, recurse=True)
                        else:
                            continue  # reparse file / other — skip
                        if _delete_entry(entry.path, to_recycle_bin=to_bin):
                            removed += 1
                            freed += sz
                        else:
                            errors += 1  # locked / in use — skipped
                    except OSError:
                        errors += 1
        total_freed += freed
        results.append(
            {
                "key": c["key"],
                "label": c["label"],
                "removed": removed,
                "bytes_freed": freed,
                "human": _human(freed),
                "errors": errors,
            }
        )
    return {"ok": True, "cleaned": results, "total_freed": total_freed, "total_human": _human(total_freed)}


